CREATE TABLE ingressos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id BIGINT NOT NULL REFERENCES eventos(id),
    cliente_id BIGINT NOT NULL REFERENCES clientes(id),
    adquirido_em TIMESTAMP NOT NULL
);
CREATE INDEX idx_ingressos_evento ON ingressos(evento_id);
CREATE INDEX idx_ingressos_evento_cliente ON ingressos(evento_id, cliente_id);
